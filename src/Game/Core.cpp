#include "stdafx.h"
#include "Core.h"
//=============================================================================
bool IsExitApp{ false };
//=============================================================================
void Print(const std::string& msg)
{
	puts(msg.c_str());
}
//=============================================================================
void Warning(const std::string& msg)
{
	Print("Warning: " + msg);
}
//=============================================================================
void Error(const std::string& msg)
{
	Print("Error: " + msg);
}
//=============================================================================
void Fatal(const std::string& msg)
{
	Print("Fatal: " + msg);
	ExitApp();
}
//=============================================================================
void ExitApp()
{
	IsExitApp = true;
}
